// ~/.config/lifelock/config — a NEW file (the locker had no config before).
// lifelock consumes five colours: the two Life tints plus accent/urgent/text.
// Read by the loader added to lifelock/src/cli.rs; picked up on next lock.

use crate::theme::{hash, Screen, Theme};

/// The five key=value lines lifelock/lifegreet share. Keys match their Cfg
/// palette fields so the loader is a straight key match. Takes a Screen so the
/// lock and login screens can carry independent colours (see theme::sync_linked).
pub fn body(s: &Screen) -> String {
    format!(
        "mature={mature}\n\
         newborn={newborn}\n\
         accent={accent}\n\
         urgent={urgent}\n\
         text={text}\n",
        mature = hash(&s.mature),
        newborn = hash(&s.newborn),
        accent = hash(&s.accent),
        urgent = hash(&s.urgent),
        text = hash(&s.text),
    )
}

pub fn render(t: &Theme) -> String {
    format!(
        "# lifelock palette — generated by lifeconf.\n\
         # Edit ~/.config/lifeconf/theme.toml (or run `lifeconf`), not this file.\n\n\
         {}",
        body(&t.lifelock)
    )
}
