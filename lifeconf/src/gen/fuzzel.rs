// fuzzel/fuzzel.ini — wholesale regen. Only [colors] is theme-derived; [main]
// and [border] are reproduced verbatim (font family follows [font], size stays
// fuzzel's own 11 per the per-consumer-size policy).

use crate::theme::{bare, Theme};

pub fn render(t: &Theme) -> String {
    let p = &t.palette;
    // Per-key alpha reproduced from the current file: the panel is slightly
    // translucent (f2), everything else opaque (ff).
    let c = |hex: &str, alpha: &str| format!("{}{}", bare(hex), alpha);

    format!(
        "# Minimal muted-olive fuzzel launcher — generated by lifeconf.\n\
         # Edit ~/.config/lifeconf/theme.toml (or run `lifeconf`), not this file.\n\n\
         [main]\n\
         font={family}:size=11\n\
         prompt=>\n\
         # Pure-text rice: no app icons (the default icon theme clashes with the olive look).\n\
         icons-enabled=no\n\
         terminal=kitty\n\
         layer=overlay\n\
         width=40\n\
         lines=12\n\
         horizontal-pad=16\n\
         vertical-pad=12\n\
         inner-pad=6\n\n\
         [colors]\n\
         background={bg}\n\
         text={text}\n\
         prompt={accent}\n\
         input={text}\n\
         match={accent}\n\
         selection={surface}\n\
         selection-text={accent}\n\
         selection-match={accent}\n\
         border={border}\n\n\
         [border]\n\
         width=1\n\
         radius=0\n",
        family = t.font.family,
        bg = c(&p.bg, "f2"),
        text = c(&p.text, "ff"),
        accent = c(&p.accent, "ff"),
        surface = c(&p.surface, "ff"),
        border = c(&p.border, "ff"),
    )
}
