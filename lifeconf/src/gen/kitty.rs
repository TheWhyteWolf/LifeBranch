// kitty/olive.conf — wholesale regen. Core surfaces map straight to roles; the
// 16 ANSI slots come from the active preset's hand-tuned [ansi] table, or from
// ansi16::derive_ansi16 when the palette is custom.

use crate::theme::{hash, Theme};

pub fn render(t: &Theme) -> String {
    let p = &t.palette;
    let ansi = match t.meta.active_preset.as_str() {
        "custom" => crate::ansi16::derive_ansi16(p),
        name => crate::presets::preset(name)
            .map(|pr| pr.ansi)
            .unwrap_or_else(|| crate::ansi16::derive_ansi16(p)),
    };

    let mut s = String::new();
    s.push_str(
        "# Muted-olive kitty theme — generated by lifeconf.\n\
         # Edit ~/.config/lifeconf/theme.toml (or run `lifeconf`), not this file.\n\
         # Included from kitty/rice.conf (install.sh appends `include rice.conf`).\n\n",
    );

    // Always emit at least one separating space: some keys (e.g.
    // inactive_tab_background, 23 chars) are wider than the pad column, and
    // relying on padding alone would glue key to value and break kitty's parse.
    let line = |s: &mut String, k: &str, v: &str| {
        s.push_str(&format!("{k:<21} {}\n", hash(v)));
    };

    line(&mut s, "foreground", &p.text);
    line(&mut s, "background", &p.bg);
    line(&mut s, "selection_foreground", &p.bg);
    line(&mut s, "selection_background", &p.accent);
    line(&mut s, "cursor", &p.accent);
    line(&mut s, "cursor_text_color", &p.bg);
    line(&mut s, "url_color", &p.accent);
    s.push('\n');
    line(&mut s, "active_border_color", &p.accent);
    line(&mut s, "inactive_border_color", &p.border);
    s.push('\n');
    line(&mut s, "active_tab_foreground", &p.bg);
    line(&mut s, "active_tab_background", &p.accent);
    line(&mut s, "inactive_tab_foreground", &p.text);
    line(&mut s, "inactive_tab_background", &p.surface);
    s.push('\n');

    let a = &ansi;
    let pair = |s: &mut String, label: &str, lo: (&str, &str), hi: (&str, &str)| {
        s.push_str(&format!("# {label}\n"));
        s.push_str(&format!("{:<7} {}\n", lo.0, hash(lo.1)));
        s.push_str(&format!("{:<7} {}\n", hi.0, hash(hi.1)));
    };
    pair(&mut s, "black", ("color0", &a.color0), ("color8", &a.color8));
    pair(&mut s, "red", ("color1", &a.color1), ("color9", &a.color9));
    pair(&mut s, "green", ("color2", &a.color2), ("color10", &a.color10));
    pair(&mut s, "yellow", ("color3", &a.color3), ("color11", &a.color11));
    pair(&mut s, "blue", ("color4", &a.color4), ("color12", &a.color12));
    pair(&mut s, "magenta", ("color5", &a.color5), ("color13", &a.color13));
    pair(&mut s, "cyan", ("color6", &a.color6), ("color14", &a.color14));
    pair(&mut s, "white", ("color7", &a.color7), ("color15", &a.color15));

    s
}
