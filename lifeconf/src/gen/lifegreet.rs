// lifegreet palette. lifegreet runs as the `greeter` system user with a
// different $HOME, so its config lives at /etc/lifegreet/config — a privileged
// path. lifeconf never escalates: it stages the file under ~/.cache and prints
// the one `sudo install` the user runs manually (plan decision §9.5).

use crate::gen::{lifelock, Report};
use crate::paths::Paths;
use crate::theme::Theme;

pub const SYSTEM_PATH: &str = "/etc/lifegreet/config";

pub fn stage(t: &Theme, paths: &Paths, r: &mut Report) {
    let staged = paths.cache("lifeconf/lifegreet-config");
    let body = format!(
        "# lifegreet palette — generated by lifeconf, staged for /etc/lifegreet/config.\n\
         # Applied via pkexec when the greeter colours change (or `lifeconf --apply-greeter`).\n\n\
         {}",
        lifelock::body(&t.lifegreet)
    );
    if let Some(dir) = std::path::Path::new(&staged).parent() {
        if let Err(e) = std::fs::create_dir_all(dir) {
            r.notes.push(format!("! {staged}: mkdir failed: {e}"));
            return;
        }
    }
    match std::fs::write(&staged, body) {
        Ok(()) => {
            r.written.push(staged.clone());
            r.notes.push(format!(
                "greeter theme staged — apply it (needs root) with:\n\
                 \x20   sudo install -Dm644 {staged} {SYSTEM_PATH}"
            ));
        }
        Err(e) => r.notes.push(format!("! {staged}: write failed: {e}")),
    }
}
